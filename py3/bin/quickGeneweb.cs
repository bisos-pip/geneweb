        #+end_org """)

        literal = cs.examples.execInsert

        cs.examples.menuChapter('=Direct GeneWeb Interface Commands=')

        cs.examples.menuSection('/Environment/')
        literal(f"export PATH={genewebInfo.gwDir}:$PATH")
        literal(f"cd {genewebInfo.basesDir}   # the tools work on bases in the current directory")

        cs.examples.menuSection('/Bases -- run as the geneweb account/')
        literal("sudo -u geneweb gwc -o family                # an empty base")
        literal("sudo -u geneweb ged2gwb /tmp/family.ged -o family   # GEDCOM -> base")
        literal("sudo -u geneweb gwb2ged family -o /tmp/family.ged   # base -> GEDCOM")
        literal("sudo -u geneweb gwu family > /tmp/family.gw  # base -> .gw text")

        cs.examples.menuSection('/gwd/')
        literal(f"curl -s -o /dev/null -w '%{{http_code}}\\n' {genewebInfo.localUrl}/{genewebInfo.demoBase}")

        cs.examples.menuSection('/systemd Unit/')
        literal("systemctl status geneweb.service")
        literal("systemctl restart geneweb.service")

        cs.examples.menuSection('/Logs -- journald only/')
        literal("journalctl -u geneweb.service -f")

        cs.examples.menuChapter('=Web UI Hints=')

        cs.examples.menuSection('/Getting In/')
        literal(f"# {genewebInfo.baseUrl}   -- the list of bases")
        literal(f"# {genewebInfo.demoUrl}   -- the demo base; wizard password {genewebInfo.wizardPassword} to edit")

        cs.examples.menuSection('/Reading Failures/')
        literal("# Base not found        -> no <name>.gwb in the bases directory, or not readable by geneweb")
        literal("# Cannot edit           -> the wizard password; -wizard in /etc/default/geneweb")

        return(cmndOutcome)


